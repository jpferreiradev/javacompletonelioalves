package JavaBasico.EstruturasRepetitivas;

public class ExemploTesteDeMesa {
    static void main() {

        int x,y;

        x = 0;
        y = 4;

        while(x < 3){
            y = y + 2;
            x = x + 1;
        }
        System.out.println(x + " - " + y);
    }
}

